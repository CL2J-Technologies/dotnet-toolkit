namespace cl2j.Database.DataAnnotations
{
    /// <summary>
    ///     What a column is in the table's primary key, and who supplies its value.
    /// </summary>
    public enum KeyType
    {
        /// <summary>
        ///     Not a key.
        /// </summary>
        None,

        /// <summary>
        ///     A primary key column whose value the library does not generate.
        ///
        ///     <para>
        ///     A single <c>int</c> or <c>long</c> is a server identity: <c>Insert</c> leaves it out of
        ///     the statement and writes the value the server picked back onto the entity
        ///     (<c>BulkInsert</c> does not read identities back). A single <c>Guid</c> is a server
        ///     default: <c>Insert</c> leaves it out and a value set on the entity is ignored. Any
        ///     other type, and any column of a composite key, is supplied by the caller and sent as
        ///     set.
        ///     </para>
        ///
        ///     <para>
        ///     <c>NewKey</c> throws for an entity that has only this kind of key.
        ///     </para>
        /// </summary>
        Key,

        /// <summary>
        ///     A <c>string</c> key that the library generates. <c>Insert</c> and <c>BulkInsert</c>
        ///     always replace the property with a new key (from the <c>IIdentifierGenerator</c>,
        ///     with the column's <c>KeyPrefix</c>), including a value set beforehand.
        ///
        ///     <para>
        ///     <c>NewKey</c> returns a key from the same generator and prefix, reserving nothing, so
        ///     it is for use outside <c>Insert</c>: <c>Insert</c> does not keep it.
        ///     </para>
        /// </summary>
        AutoGeneratedKey,

        /// <summary>
        ///     A <c>string</c> key that the caller supplies. <c>Insert</c> and <c>BulkInsert</c> send
        ///     the value as set and never generate one, so a key left empty is inserted empty.
        ///
        ///     <para>
        ///     <c>NewKey</c> is how the caller gets a value to set: a key from the generator, with
        ///     the column's <c>KeyPrefix</c>, set on the entity before the insert.
        ///     </para>
        /// </summary>
        SelfGeneratedKey
    }
}
