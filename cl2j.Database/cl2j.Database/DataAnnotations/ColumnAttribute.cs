namespace cl2j.Database.DataAnnotations
{
    [AttributeUsage(AttributeTargets.Property | AttributeTargets.Field)]
    public class ColumnAttribute : Attribute
    {
        /// <summary>
        ///     The name of the column the property is mapped to.
        /// </summary>
        public string Name { get; set; } = string.Empty;

        /// <summary>
        ///     The database provider specific data type of the column the property is mapped to.
        /// </summary>
        public string TypeName { get; set; } = string.Empty;

        /// <summary>
        ///     Maximum allowable length of the data.
        /// </summary>
        public int Length { get; set; }

        /// <summary>
        ///     Number of decimals.
        /// </summary>
        public int Decimals { get; set; }

        /// <summary>
        ///     Indicate if the attribute is a key and the type of the key. See <see cref="KeyType"/>
        ///     for what each value means at run time.
        ///
        ///     <para>
        ///     None: not a key. Key: a primary key the library does not generate (a single int or long
        ///     is a server identity written back on insert, a single Guid a server default, anything
        ///     else is supplied by the caller). AutoGeneratedKey: a string key the library generates
        ///     on insert, replacing any value set. SelfGeneratedKey: a string key the caller supplies
        ///     (<c>NewKey</c> provides one), sent as set.
        ///     </para>
        /// </summary>
        public KeyType Key { get; set; } = KeyType.None;

        /// <summary>
        ///     Indicate that a property, field is required.
        /// </summary>
        public bool Required { get; set; }

        /// <summary>
        ///     Indicate that the property is serialized as a JSON.
        /// </summary>
        public bool Json { get; set; }

        /// <summary>
        ///     The property default value
        /// </summary>
        public string? Default { get; set; } = "";


        /// <summary>
        ///     The prefix to prepend to the generated key
        /// </summary>
        public string? KeyPrefix { get; set; }
    }
}
