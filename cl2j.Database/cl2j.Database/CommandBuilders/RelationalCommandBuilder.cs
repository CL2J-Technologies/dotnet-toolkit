using System.Data.Common;
using cl2j.Database.DataAnnotations;
using cl2j.Database.Descriptors;
using cl2j.Database.Exceptions;
using cl2j.Database.Helpers;

namespace cl2j.Database.CommandBuilders
{
    /// <summary>
    ///     A default implementation of <see cref="ICommandBuilder"/> and <see cref="IDatabaseFormatter"/>
    ///     for a relational database that speaks SQL close to SQL Server's. A provider derives from it
    ///     and implements only what differs: how identifiers are quoted, how CLR types map to column
    ///     types, how a key is declared, how the generated identity is read back, and how rows are bulk
    ///     loaded.
    ///
    ///     <para>
    ///     Every statement is built by <see cref="CommandBuilderHelpers"/> through this class's
    ///     formatter members, so a provider changes the text of a statement by overriding one of
    ///     those members, or the statement method itself (all are <c>virtual</c>).
    ///     </para>
    ///
    ///     <para>
    ///     What a provider must implement: <see cref="Support"/>, <see cref="QuoteIdentifier"/>,
    ///     <see cref="MapClrType"/>, <see cref="GetJsonColumnType"/>, <see cref="IdentityKeyDeclaration"/>,
    ///     <see cref="GuidKeyDeclaration"/>, <see cref="GetIdentityRetrieval"/>, <see cref="WriteBulkAsync"/>,
    ///     and one of <see cref="DefaultSchemaName"/> or <see cref="CurrentSchemaExpression"/>.
    ///     Optional: <see cref="MaxKeysPerStatement"/>, <see cref="PrepareParameter"/>, and any
    ///     virtual member.
    ///     </para>
    /// </summary>
    public abstract class RelationalCommandBuilder : ICommandBuilder, IDatabaseFormatter
    {
        private readonly IIdentifierGenerator identifierGenerator;

        /// <param name="identifierGenerator">
        ///     Generates the value of an <c>AutoGeneratedKey</c> column. <c>null</c> selects
        ///     <see cref="GuidIdentifierGenerator.Default"/>.
        /// </param>
        protected RelationalCommandBuilder(IIdentifierGenerator? identifierGenerator)
        {
            this.identifierGenerator = identifierGenerator ?? GuidIdentifierGenerator.Default;
        }

        #region ICommandBuilder

        /// <summary>
        ///     True when this builder serves the connection, which is how
        ///     <see cref="CommandBuilderFactory.GetCommandBuilder"/> picks one. Test the connection's
        ///     type: SQL Server <c>connection is SqlConnection</c>, MySQL <c>MySqlConnection</c>,
        ///     PostgreSQL <c>NpgsqlConnection</c>.
        /// </summary>
        public abstract bool Support(DbConnection connection);

        /// <summary>
        ///     This builder: it is its own formatter.
        /// </summary>
        public IDatabaseFormatter DatabaseFormatter => this;

        /// <summary>
        ///     The generator passed to the constructor, or <see cref="GuidIdentifierGenerator.Default"/>.
        /// </summary>
        public IIdentifierGenerator IdentifierGenerator => identifierGenerator;

        /// <summary>
        ///     The most keys a single query-by-keys statement carries. Defaults to
        ///     <see cref="QueryKeyBatches.MaxKeysPerStatement"/> (2000), which fits under the
        ///     smallest parameter limit of the three known providers (SQL Server 2100; PostgreSQL
        ///     65,535; MySQL has no practical one). Override to batch less or more. Must be greater
        ///     than zero.
        /// </summary>
        public virtual int MaxKeysPerStatement => QueryKeyBatches.MaxKeysPerStatement;

        /// <summary>
        ///     Called for every parameter the library binds, after it has set value, type, size and
        ///     precision and before the command runs. The default does nothing. PostgreSQL overrides
        ///     it to convert a <c>DateTimeOffset</c> to UTC and to mark a JSON column as <c>jsonb</c>.
        ///     Not called by the bulk path, which writes values itself.
        /// </summary>
        public virtual void PrepareParameter(DbParameter parameter, ColumnDescriptor? column) { }

        /// <summary>
        ///     Asks <c>INFORMATION_SCHEMA.TABLES</c> whether the table is there, as one scalar
        ///     (1 or 0). The catalog is queried rather than the table itself so that a failure of any
        ///     other kind (dropped connection, timeout, missing permission) is an exception, not "no".
        ///
        ///     <para>
        ///     It used to be <c>SELECT TOP 1 *</c> against the table itself, with the caller
        ///     catching every exception and reading one as "no". Anything that went wrong therefore
        ///     came back as "the table does not exist": a dropped connection, a timeout, a missing
        ///     SELECT permission. <c>CreateTableIfRequired</c> would then try to create a table that
        ///     was already there. See issue #27's neighbours.
        ///     </para>
        ///
        ///     <para>
        ///     The schema predicate is <c>@tableSchema</c> when the type names a schema, or when
        ///     <see cref="DefaultSchemaName"/> is not <c>null</c> (then the type's schema, else that
        ///     name, is bound). Otherwise it is <see cref="CurrentSchemaExpression"/>, evaluated by
        ///     the server, and no schema parameter is bound.
        ///     </para>
        /// </summary>
        public virtual TextStatement GetTableExistsStatement(Type type)
        {
            var tableDescriptor = TableDescriptorFactory.Create(type, this);

            //A schema is bound when someone names one; otherwise the server's current one decides,
            //unless the provider has a fixed default (SQL Server puts a table in dbo).
            var schema = tableDescriptor.Schema ?? DefaultSchemaName;
            var schemaPredicate = schema is null ? CurrentSchemaExpression : FormatParameterName("tableSchema");

            var statement = new TextStatement
            {
                TableDescriptor = tableDescriptor,
                Text = $"""
                    SELECT CASE WHEN EXISTS (
                        SELECT 1 FROM INFORMATION_SCHEMA.TABLES
                        WHERE TABLE_NAME = {FormatParameterName("tableName")} AND TABLE_SCHEMA = {schemaPredicate}
                    ) THEN 1 ELSE 0 END
                    """
            };

            statement.Parameters.Add(new StatementParameter("tableName", tableDescriptor.Name));
            if (schema is not null)
                statement.Parameters.Add(new StatementParameter("tableSchema", schema));

            return statement;
        }

        /// <summary>
        ///     The schema a table lands in when its type names none, for a server where that is a
        ///     fixed name. SQL Server returns <c>"dbo"</c>. The default is <c>null</c>, which makes
        ///     <see cref="GetTableExistsStatement"/> use <see cref="CurrentSchemaExpression"/>.
        /// </summary>
        protected virtual string? DefaultSchemaName => null;

        /// <summary>
        ///     A SQL expression for the schema the connection currently resolves unqualified names
        ///     in, used when the type names no schema and <see cref="DefaultSchemaName"/> is
        ///     <c>null</c>. MySQL returns <c>DATABASE()</c> (it calls a database what others call a
        ///     schema), PostgreSQL <c>current_schema()</c>. A provider must override this or
        ///     <see cref="DefaultSchemaName"/>; the default throws.
        /// </summary>
        protected virtual string CurrentSchemaExpression
            => throw new NotSupportedException($"'{GetType().Name}' must override either DefaultSchemaName or CurrentSchemaExpression so the table-exists statement knows which schema to look in.");

        /// <summary>
        ///     <c>DROP TABLE</c> of the type's table.
        /// </summary>
        public virtual TextStatement GetDropTableStatement(Type type)
            => CommandBuilderHelpers.GetDropTableStatement(type, this);

        /// <summary>
        ///     <c>CREATE TABLE</c> for the type, with column types from <see cref="GetColumnDataType"/>
        ///     and key declarations from <see cref="GetColumnKeyType"/>.
        /// </summary>
        public virtual TextStatement GetCreateTableStatement(Type type)
            => CommandBuilderHelpers.GetCreateTableStatement(type, this);

        /// <summary>
        ///     The insert, followed by <see cref="GetIdentityRetrieval"/> when the table has an
        ///     identity key (<see cref="CommandBuilderHelpers.IsIdentity"/>: <c>KeyType.Key</c> on an
        ///     <c>int</c> or <c>long</c>), so that executing the statement as a scalar returns the
        ///     number the server picked. A string key travels in the insert and a Guid key comes from
        ///     a column default, so neither gets a suffix.
        ///
        ///     <para>
        ///     <c>Insert</c> ends in <c>ExecuteScalarAsync</c> and returns what it gets, and
        ///     <c>Insert&lt;TIn, TOut&gt;</c> exists to hand that value back typed. A plain
        ///     <c>INSERT ... VALUES</c> produces no result set, so both returned nothing — always
        ///     <c>null</c>, always <c>default</c>. The one thing a caller wants after inserting a
        ///     row with a generated key was the one thing they could not get.
        ///     </para>
        /// </summary>
        public virtual TextStatement GetInsertStatement(Type type)
        {
            var statement = CommandBuilderHelpers.GetInsertStatement(type, this);

            var identity = statement.TableDescriptor.Keys.FirstOrDefault(CommandBuilderHelpers.IsIdentity);
            if (identity is not null)
                statement.Text += GetIdentityRetrieval(statement.TableDescriptor, identity);

            return statement;
        }

        /// <summary>
        ///     The text appended to the insert to read back the identity just generated, for an
        ///     <c>int</c> or <c>long</c> key. Include the separator the server needs.
        ///
        ///     <para>
        ///     Invariant: executing the whole statement as a scalar must yield exactly one scalar
        ///     (the identity), because the caller reads the first column of the first row. The value
        ///     may be any numeric type: the library converts it to the type the caller asked for.
        ///     </para>
        ///
        ///     <para>
        ///     SQL Server: <c>;SELECT CAST(SCOPE_IDENTITY() AS int)</c> (<c>bigint</c> for a
        ///     <c>long</c> key). MySQL: <c>;SELECT LAST_INSERT_ID()</c>. PostgreSQL:
        ///     <c> RETURNING "Id"</c>.
        ///     </para>
        /// </summary>
        /// <param name="table">The table inserted into.</param>
        /// <param name="identity">The identity column, as selected by <see cref="CommandBuilderHelpers.IsIdentity"/>.</param>
        protected abstract string GetIdentityRetrieval(TableDescriptor table, ColumnDescriptor identity);

        /// <summary>
        ///     <c>UPDATE</c> of every non-key column, filtered by the keys.
        /// </summary>
        public virtual TextStatement GetUpdateStatement(Type type)
            => CommandBuilderHelpers.GetUpdateStatement(type, this);

        /// <summary>
        ///     <c>UPDATE</c> of one named non-key column, filtered by the keys.
        /// </summary>
        public virtual TextStatement GetUpdateColumnStatement(Type type, string columnName)
            => CommandBuilderHelpers.GetUpdateColumnStatement(type, columnName, this);

        /// <summary>
        ///     <c>DELETE</c> filtered by the keys.
        /// </summary>
        public virtual TextStatement GetDeleteStatement(Type type)
            => CommandBuilderHelpers.GetDeleteStatement(type, this);

        /// <summary>
        ///     <c>SELECT</c> of every column of the type, unfiltered.
        /// </summary>
        public virtual TextStatement GetQueryStatement(Type type)
            => CommandBuilderHelpers.GetQueryStatement(type, this);

        /// <summary>
        ///     <c>SELECT</c> filtered by one equality predicate per column of <paramref name="paramType"/>.
        /// </summary>
        public virtual TextStatement GetQueryStatement(Type type, Type paramType)
            => CommandBuilderHelpers.GetQueryStatement(type, paramType, this);

        /// <summary>
        ///     <c>SELECT</c> filtered by the key column(s).
        /// </summary>
        public virtual TextStatement GetQueryByKeyStatement(Type type)
            => CommandBuilderHelpers.GetQueryByKeyStatement(type, this);

        /// <summary>
        ///     <c>SELECT</c> filtered by <c>key IN (...)</c> with one generated parameter per value.
        ///     The table must have exactly one key. The caller splits long lists by
        ///     <see cref="MaxKeysPerStatement"/>.
        /// </summary>
        public virtual TextStatement GetQueryByKeysStatement(Type type, IEnumerable<object> values)
            => CommandBuilderHelpers.GetQueryByKeysStatement(type, values, this);

        /// <summary>
        ///     The shared preamble of a bulk insert: it builds the descriptor, selects the columns an
        ///     <c>INSERT</c> would write (everything except what the server supplies, see
        ///     <see cref="CommandBuilderHelpers.IsSuppliedByTheServer"/>), turns the items into a
        ///     <see cref="System.Data.DataTable"/> and hands all three to <see cref="WriteBulkAsync"/>.
        ///     Not virtual: a provider's work goes in <see cref="WriteBulkAsync"/>.
        /// </summary>
        public async Task BulkInsert<TIn>(DbConnection connection, IEnumerable<TIn> items, CancellationToken cancellationToken, DbTransaction? transaction = null)
        {
            var tableDescriptor = TableDescriptorFactory.Create(typeof(TIn), this);
            //The same columns as INSERT: only the keys the server fills in are left out.
            var columns = tableDescriptor.Columns.Where(c => !CommandBuilderHelpers.IsSuppliedByTheServer(c)).ToList();

            var dataTable = DataTableHelpers.CreateDataTable(items, tableDescriptor.NameFormatted, columns);

            await WriteBulkAsync(connection, tableDescriptor, columns, dataTable, cancellationToken, transaction);
        }

        /// <summary>
        ///     Writes the rows to the table with the provider's fastest path: <c>SqlBulkCopy</c> on
        ///     SQL Server, binary <c>COPY</c> on PostgreSQL, <c>MySqlBulkCopy</c> or batched multi-row
        ///     <c>INSERT</c> on MySQL.
        ///
        ///     <para>
        ///     Cast <paramref name="connection"/> and <paramref name="transaction"/> to the provider's
        ///     types and throw a <see cref="DatabaseException"/> naming the type received when the
        ///     connection is of the wrong kind. <paramref name="rows"/> holds one column per entry of
        ///     <paramref name="columns"/>, in the same order, with values already prepared (JSON
        ///     serialized, defaults applied); an empty table means there is nothing to write.
        ///     </para>
        /// </summary>
        /// <param name="connection">An open connection that <see cref="Support"/> accepted.</param>
        /// <param name="table">The destination table.</param>
        /// <param name="columns">The columns to write: identity and server-generated keys are not among them, a string key is.</param>
        /// <param name="rows">The values, one <see cref="System.Data.DataColumn"/> per entry of <paramref name="columns"/>.</param>
        /// <param name="cancellationToken">Cancellation of the write.</param>
        /// <param name="transaction">The caller's transaction, or <c>null</c>.</param>
        //The order mirrors ICommandBuilder.BulkInsert (token, then the optional transaction), which is
        //what a caller of the extension sees; reordering here would make the two read differently.
        [System.Diagnostics.CodeAnalysis.SuppressMessage("Design", "CA1068:CancellationToken parameters must come last", Justification = "Mirrors ICommandBuilder.BulkInsert, where the transaction follows the token.")]
        protected abstract Task WriteBulkAsync(DbConnection connection, TableDescriptor table, IReadOnlyList<ColumnDescriptor> columns, System.Data.DataTable rows, CancellationToken cancellationToken, DbTransaction? transaction);

        #endregion

        #region IDatabaseFormatter

        /// <summary>
        ///     Quotes one identifier (a table, schema or column name) so it is safe as a name and
        ///     case-sensitive where the server allows. SQL Server returns <c>[name]</c>, MySQL
        ///     <c>`name`</c> and PostgreSQL <c>"name"</c>; the latter two double an embedded quote.
        /// </summary>
        protected abstract string QuoteIdentifier(string name);

        /// <summary>
        ///     The table name quoted by <see cref="QuoteIdentifier"/>, prefixed by the quoted schema
        ///     and a dot when there is one.
        /// </summary>
        public virtual string FormatTableName(string table, string? schema = null)
        {
            if (schema is null)
                return QuoteIdentifier(table);
            return $"{QuoteIdentifier(schema)}.{QuoteIdentifier(table)}";
        }

        /// <summary>
        ///     The column name quoted by <see cref="QuoteIdentifier"/>.
        /// </summary>
        public virtual string FormatColumnName(string name)
            => QuoteIdentifier(name);

        /// <summary>
        ///     The parameter marker for a name: <c>@name</c>, which all three known providers use.
        /// </summary>
        public virtual string FormatParameterName(string name)
            => "@" + name;

        /// <summary>
        ///     The column type for a property, then <c>DEFAULT x</c> when the column declares one.
        ///
        ///     <para>
        ///     In order: an explicit <c>TypeName</c> wins; a <c>Json</c> column takes
        ///     <see cref="GetJsonColumnType"/>; otherwise <c>Nullable&lt;T&gt;</c> is unwrapped and
        ///     <see cref="MapClrType"/> decides, and a <c>null</c> from it is a
        ///     <see cref="DatabaseException"/> asking for a <c>TypeName</c>. There is deliberately no
        ///     silent fallback type.
        ///     </para>
        /// </summary>
        public virtual string GetColumnDataType(ColumnDescriptor column)
        {
            var columnAttr = column.ColumnAtribute;

            string propertyTypeDesc;

            if (!string.IsNullOrEmpty(columnAttr.TypeName))
                propertyTypeDesc = columnAttr.TypeName;
            else if (columnAttr.Json)
                propertyTypeDesc = GetJsonColumnType(columnAttr);
            else
            {
                //Nullable<T> is not the type it wraps, so every nullable value type used to miss
                //every branch of the type map and land on the varchar(MAX) default: an ordinary
                //"int?" column was created as text. Unwrap first, once. See issue #27.
                var type = Nullable.GetUnderlyingType(column.Property.PropertyType) ?? column.Property.PropertyType;

                //No silent fallback. A varchar(MAX) default is how a Guid came to be stored as
                //text without anyone noticing, and how every nullable column did the same. A type
                //nobody mapped is a failure at schema creation, which is the cheapest moment to
                //find it; TypeName remains the way to say what the column should be.
                propertyTypeDesc = MapClrType(type, column)
                    ?? throw new DatabaseException($"No column type for '{type.Name}' on '{column.Name}'. Declare one with [Column(TypeName = \"...\")].");
            }

            if (!string.IsNullOrEmpty(columnAttr.Default))
                propertyTypeDesc += $" DEFAULT {columnAttr.Default}";

            return propertyTypeDesc;
        }

        /// <summary>
        ///     The column type for a CLR type, or <c>null</c> when the provider has none (the caller
        ///     then throws a <see cref="DatabaseException"/> asking for a <c>TypeName</c>).
        ///
        ///     <para>
        ///     <paramref name="type"/> is already unwrapped from <c>Nullable&lt;T&gt;</c>, and may be
        ///     an enum. Cover: enum, bool, byte, short, int, long, double, float, decimal (through
        ///     <see cref="FormatDecimal"/>), Guid, string, byte[], DateTimeOffset, DateTime,
        ///     DateOnly, TimeOnly, TimeSpan and char. Examples for <c>int</c>: SQL Server <c>int</c>,
        ///     MySQL <c>int</c>, PostgreSQL <c>integer</c>; for <c>string</c> without a length: SQL
        ///     Server <c>varchar(max)</c>, MySQL <c>longtext</c>, PostgreSQL <c>text</c>.
        ///     </para>
        /// </summary>
        /// <param name="type">The property type with <c>Nullable&lt;T&gt;</c> removed.</param>
        /// <param name="column">The column, for its <c>Length</c> and <c>Decimals</c>.</param>
        protected abstract string? MapClrType(Type type, ColumnDescriptor column);

        /// <summary>
        ///     The column type of a property marked <c>Json</c>. SQL Server: <c>varchar(max)</c>
        ///     (<c>varchar(n)</c> with a length); MySQL: <c>json</c>; PostgreSQL: <c>jsonb</c>, each
        ///     <c>varchar(n)</c> when the attribute gives a <c>Length</c>.
        /// </summary>
        /// <param name="attribute">The column attribute, for its <c>Length</c>.</param>
        protected abstract string GetJsonColumnType(ColumnAttribute attribute);

        /// <summary>
        ///     <c>typeName(Length,Decimals)</c>, for a provider's <see cref="MapClrType"/>. A decimal
        ///     needs its precision declared: without <c>Length</c> the column would be a bare
        ///     <c>decimal</c>, which SQL Server reads as <c>decimal(18,0)</c> — an amount of 12.34
        ///     stored as 12, rounded on the way in with nothing to say so. Refusing is louder than
        ///     guessing a precision the caller did not choose. See issue #27.
        /// </summary>
        /// <param name="attribute">The column attribute holding <c>Length</c> (precision) and <c>Decimals</c> (scale).</param>
        /// <param name="typeName">The decimal type's name: <c>decimal</c> (SQL Server, MySQL) or <c>numeric</c> (PostgreSQL).</param>
        /// <exception cref="DatabaseException">The attribute has no <c>Length</c>.</exception>
        protected static string FormatDecimal(ColumnAttribute attribute, string typeName = "decimal")
        {
            if (attribute.Length <= 0)
                throw new DatabaseException("A decimal column needs its precision: [Column(Length = 18, Decimals = 2)].");

            return $"{typeName}({attribute.Length},{attribute.Decimals})";
        }

        /// <summary>
        ///     What follows the data type of a key column in <c>CREATE TABLE</c>: an <c>int</c> or
        ///     <c>long</c> gets <see cref="IdentityKeyDeclaration"/>, a string gets <c>" NOT NULL"</c>
        ///     (its primary-key constraint is a separate line), a Guid gets
        ///     <see cref="GuidKeyDeclaration"/>, and any other type is a <see cref="DatabaseException"/>.
        ///
        ///     <para>
        ///     Appended after the data type <see cref="GetColumnDataType"/> already wrote, so it must
        ///     not repeat it.
        ///     </para>
        /// </summary>
        public virtual string GetColumnKeyType(ColumnDescriptor column)
        {
            //Appended after the data type GetColumnDataType already wrote, so it must not repeat it:
            //the Guid branch used to add a second UNIQUEIDENTIFIER. A long key was refused outright,
            //although INSERT and IsSuppliedByTheServer already treat it as an identity.
            var type = column.Property.PropertyType;

            if (type == Types.TypeInt || type == Types.TypeLong)
                return IdentityKeyDeclaration;
            else if (type == Types.TypeString)
                return " NOT NULL";
            else if (type == Types.TypeGuid)
                return GuidKeyDeclaration;

            throw new DatabaseException($"Unsupported key type '{type.Name}'");
        }

        /// <summary>
        ///     The declaration that makes an <c>int</c> or <c>long</c> key an auto-incremented
        ///     primary key, with a leading space. SQL Server: <c> IDENTITY(1,1) PRIMARY KEY</c>;
        ///     MySQL: <c> AUTO_INCREMENT PRIMARY KEY</c>; PostgreSQL:
        ///     <c> GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY</c> (<c>BY DEFAULT</c>, not
        ///     <c>ALWAYS</c>, so an explicit value is still accepted).
        /// </summary>
        protected abstract string IdentityKeyDeclaration { get; }

        /// <summary>
        ///     The declaration that makes a <c>Guid</c> key a primary key the server fills in, with a
        ///     leading space. SQL Server: <c> DEFAULT NEWID() PRIMARY KEY</c>; MySQL:
        ///     <c> DEFAULT (UUID()) PRIMARY KEY</c>; PostgreSQL:
        ///     <c> DEFAULT gen_random_uuid() PRIMARY KEY</c>.
        /// </summary>
        protected abstract string GuidKeyDeclaration { get; }

        #endregion
    }
}
