    /// <summary>
    ///     One column per branch of the data-type skeleton.
    /// </summary>
    [Table("TpColumns")]
    public sealed class TpColumnsRow
    {
        [Column(Name = "Declared", TypeName = "CUSTOMTYPE")]
        public int Declared { get; set; }

        [Column(Name = "Document", Json = true)]
        public string? Document { get; set; }

        [Column(Name = "BoundedDocument", Json = true, Length = 200)]
        public string? BoundedDocument { get; set; }

        [Column(Name = "Plain")]
        public int Plain { get; set; }

        [Column(Name = "Optional")]
        public int? Optional { get; set; }

        [Column(Name = "Kind")]
        public TpKind Kind { get; set; }

        [Column(Name = "Unmapped")]
        public Version? Unmapped { get; set; }

        [Column(Name = "WithDefault", Default = "7")]
        public int WithDefault { get; set; }

        [Column(Name = "Price", Length = 18, Decimals = 2)]
        public decimal Price { get; set; }

        [Column(Name = "NoPrecision")]
        public decimal NoPrecision { get; set; }

        [Column(Name = "DeclaredWithDefault", TypeName = "CUSTOMTYPE", Default = "1")]
        public int DeclaredWithDefault { get; set; }
    }

    public enum TpKind
    {
        None,
        Some
    }

    /// <summary>
    ///     The entity the <c>ConnectionExtensions</c> paths run against.
