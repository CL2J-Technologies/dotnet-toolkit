using System.Data;
using System.Data.Common;
using System.Globalization;
using cl2j.Database.CommandBuilders;
using cl2j.Database.DataAnnotations;
using cl2j.Database.Descriptors;
using cl2j.Database.Exceptions;
using cl2j.Database.Helpers;
using Npgsql;
using NpgsqlTypes;

namespace cl2j.Database.PostgreSql
{
    /// <summary>
    ///     The PostgreSQL provider, on <c>Npgsql</c>. Requires PostgreSQL 13 or later: a Guid key is
    ///     declared <c>DEFAULT gen_random_uuid()</c>, which is built in from 13 (it needed the
    ///     pgcrypto extension before).
    ///
    ///     <para>
    ///     Every statement comes from <see cref="RelationalCommandBuilder"/>. What is PostgreSQL's
    ///     own: quoting, the type map, the identity retrieval (<c>RETURNING</c>), the three
    ///     parameter adjustments Npgsql needs (<see cref="PrepareParameter"/>) and the bulk load
    ///     (binary <c>COPY</c>).
    ///     </para>
    /// </summary>
    internal sealed class PostgreSqlCommandBuilder(IIdentifierGenerator? identifierGenerator) : RelationalCommandBuilder(identifierGenerator)
    {
        public override bool Support(DbConnection connection)
        {
            return connection is NpgsqlConnection;
        }

        //A table whose type names no schema lives in the first schema of the search path, which
        //current_schema() reports.
        protected override string CurrentSchemaExpression => "current_schema()";

        /// <summary>
        ///     A double quote inside a name is doubled. Quoting also stops PostgreSQL folding the
        ///     name to lower case, so what the type declares is what the catalog holds, and
        ///     "RoundTrip" and roundtrip are two different tables.
        /// </summary>
        protected override string QuoteIdentifier(string name)
        {
            return "\"" + name.Replace("\"", "\"\"", StringComparison.Ordinal) + "\"";
        }

        /// <summary>
        ///     The column keeps the type it was declared with (<c>integer</c> or <c>bigint</c>), so
        ///     <c>Insert&lt;TIn, int&gt;</c> and <c>Insert&lt;TIn, long&gt;</c> get exactly that
        ///     type back.
        /// </summary>
        protected override string GetIdentityRetrieval(TableDescriptor table, ColumnDescriptor identity)
        {
            return $" RETURNING {identity.NameFormatted}";
        }

        /// <summary>
        ///     <c>GENERATED BY DEFAULT</c> rather than <c>ALWAYS</c>: the latter refuses an explicit
        ///     value, and a caller may well want to seed a row.
        /// </summary>
        protected override string IdentityKeyDeclaration => " GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY";

        protected override string GuidKeyDeclaration => " DEFAULT gen_random_uuid() PRIMARY KEY";

        protected override string GetJsonColumnType(ColumnAttribute attribute)
        {
            return attribute.Length <= 0 ? "jsonb" : $"varchar({attribute.Length})";
        }

        /// <summary>
        ///     The SQL Server mapping, translated. The differences that matter to a caller:
        ///     <list type="bullet">
        ///         <item><c>string</c> without a length is <c>text</c>, stored exactly like
        ///         <c>varchar</c>. With a length it is <c>varchar(n)</c>, counted in characters.</item>
        ///         <item><c>DateTimeOffset</c> is <c>timestamptz</c>: the instant is kept, the offset
        ///         is not, and Npgsql refuses to write an offset other than zero.</item>
        ///         <item><c>DateTime</c> is <c>timestamp</c> (no time zone), like SQL Server's
        ///         <c>datetime2</c>: no kind is stored.</item>
        ///         <item><c>byte</c> is <c>smallint</c>: PostgreSQL has no one-byte integer.</item>
        ///         <item><c>TimeSpan</c> is <c>interval</c>, a duration: it is not limited to a day.</item>
        ///         <item>Temporal types carry six fractional digits; .NET has seven.</item>
        ///     </list>
        /// </summary>
        protected override string? MapClrType(Type type, ColumnDescriptor column)
        {
            var columnAttr = column.ColumnAtribute;

            if (type.IsEnum)
                return "integer";
            if (type == Types.TypeBool)
                return "boolean";
            if (type == Types.TypeByte || type == Types.TypeShort)
                return "smallint";
            if (type == Types.TypeInt)
                return "integer";
            if (type == Types.TypeLong)
                return "bigint";
            if (type == Types.TypeDouble)
                return "double precision";
            if (type == Types.TypeFloat)
                return "real";
            if (type == Types.TypeDecimal)
                return FormatDecimal(columnAttr, "numeric");
            if (type == Types.TypeGuid)
                return "uuid";
            if (type == Types.TypeString)
                return columnAttr.Length > 0 ? $"varchar({columnAttr.Length})" : "text";
            if (type == Types.TypeByteArray)
                return "bytea";
            if (type == Types.TypeDateTimeOffset)
                return "timestamptz";
            if (type == Types.TypeDateTime)
                return "timestamp";
            if (type == Types.TypeDateOnly)
                return "date";
            if (type == Types.TypeTimeOnly)
                return "time";
            if (type == Types.TypeTimeSpan)
                return "interval";
            if (type == Types.TypeChar)
                return "char(1)";

            return null;
        }

        /// <summary>
        ///     Three adjustments, each for a value Npgsql would otherwise refuse or misplace:
        ///     <list type="bullet">
        ///         <item>a <see cref="DateTimeOffset"/> becomes UTC: <c>timestamptz</c> takes no other offset;</item>
        ///         <item>a <see cref="DateTime"/> becomes <see cref="DateTimeKind.Unspecified"/>: the core binds
        ///         it as <see cref="DbType.DateTime2"/>, i.e. <c>timestamp</c>, which refuses a Utc one;</item>
        ///         <item>a JSON column's string is typed <c>jsonb</c>, so the server does not see text where it expects
        ///         <c>jsonb</c> and no cast is written into the SQL.</item>
        ///     </list>
        ///     None of them changes the value: the instant, the ticks and the document stay as they were.
        /// </summary>
        public override void PrepareParameter(DbParameter parameter, ColumnDescriptor? column)
        {
            switch (parameter.Value)
            {
                case DateTimeOffset moment:
                    parameter.Value = moment.ToUniversalTime();
                    break;
                case DateTime stamp when stamp.Kind != DateTimeKind.Unspecified:
                    parameter.Value = DateTime.SpecifyKind(stamp, DateTimeKind.Unspecified);
                    break;
            }

            if (parameter is NpgsqlParameter npgsql && column is not null && JsonType(column) is { } json)
                npgsql.NpgsqlDbType = json;
        }

        /// <summary>
        ///     The Npgsql type of a JSON column, or <c>null</c> when it is not one the library can
        ///     type: <c>jsonb</c> when it declares nothing, as declared when it says <c>json</c> or
        ///     <c>jsonb</c>, and none for a <c>Length</c> (a <c>varchar</c>, bound as text).
        /// </summary>
        private static NpgsqlDbType? JsonType(ColumnDescriptor column)
        {
            var attribute = column.ColumnAtribute;
            if (!attribute.Json)
                return null;

            if (string.IsNullOrWhiteSpace(attribute.TypeName))
                return attribute.Length <= 0 ? NpgsqlDbType.Jsonb : null;

            var typeName = attribute.TypeName.TrimStart();
            if (typeName.StartsWith("jsonb", StringComparison.OrdinalIgnoreCase))
                return NpgsqlDbType.Jsonb;
            if (typeName.StartsWith("json", StringComparison.OrdinalIgnoreCase))
                return NpgsqlDbType.Json;

            return null;
        }

        /// <summary>
        ///     Binary <c>COPY</c> (<see cref="NpgsqlConnection.BeginBinaryImportAsync(string, CancellationToken)"/>),
        ///     the equivalent of <c>SqlBulkCopy</c>.
        ///
        ///     <para>
        ///     <b>All or nothing.</b> A COPY is one statement: a duplicate key, a value the column
        ///     refuses, a cancellation or a dropped connection leaves no row behind. The importer is
        ///     completed only after the last row, and disposing it before that cancels the COPY. An
        ///     empty input writes nothing and does not touch the server. Inside a transaction the
        ///     rows commit and roll back with it.
        ///     </para>
        ///
        ///     <para>
        ///     Binary COPY is strict: each value must be written with the type of its column, or the
        ///     server refuses the stream. The type is therefore chosen per column from the property
        ///     type, mirroring <see cref="MapClrType"/>. Npgsql has no per-importer transaction: the
        ///     COPY runs in the connection's current one, which is why the transaction given must be
        ///     the connection's own.
        ///     </para>
        /// </summary>
        protected override async Task WriteBulkAsync(DbConnection connection, TableDescriptor table, IReadOnlyList<ColumnDescriptor> columns, DataTable rows, CancellationToken cancellationToken, DbTransaction? transaction)
        {
            var npgsqlConnection = connection as NpgsqlConnection ?? throw new DatabaseException($"NpgsqlConnection required. '{connection.GetType().Name}' received.");

            if (transaction is not null && !ReferenceEquals(transaction.Connection, connection))
                throw new DatabaseException("The transaction does not belong to the connection.");

            if (rows.Rows.Count == 0)
                return;

            //Columns are matched by name, not by position.
            var ordinals = columns.Select(c => rows.Columns[c.Name]?.Ordinal ?? throw new DatabaseException($"The column '{c.Name}' is missing from the rows to write.")).ToArray();

            //Checked before the COPY starts: Npgsql breaks the connection when a token is cancelled
            //in the middle of the protocol exchange, and a token that is already cancelled should
            //leave the connection as it found it.
            cancellationToken.ThrowIfCancellationRequested();

            var copy = $"COPY {table.NameFormatted} ({string.Join(',', columns.Select(c => c.NameFormatted))}) FROM STDIN (FORMAT BINARY)";

            await using var writer = await npgsqlConnection.BeginBinaryImportAsync(copy, cancellationToken);
            writer.Timeout = TimeSpan.FromSeconds(ConnectionExtensions.DatabaseOptions.GetBulkInsertTimeoutSeconds(connection.ConnectionTimeout));

            foreach (DataRow row in rows.Rows)
            {
                cancellationToken.ThrowIfCancellationRequested();

                await writer.StartRowAsync(cancellationToken);
                for (var c = 0; c < columns.Count; c++)
                {
                    var value = row[ordinals[c]];
                    if (value is DBNull)
                        await writer.WriteNullAsync(cancellationToken);
                    else
                        await WriteValue(writer, columns[c], value, cancellationToken);
                }
            }

            await writer.CompleteAsync(cancellationToken);
        }

        private static async Task WriteValue(NpgsqlBinaryImporter writer, ColumnDescriptor column, object value, CancellationToken cancellationToken)
        {
            var attribute = column.ColumnAtribute;
            var type = Nullable.GetUnderlyingType(column.Property.PropertyType) ?? column.Property.PropertyType;

            if (JsonType(column) is { } jsonType)
                await writer.WriteAsync((string)value, jsonType, cancellationToken);
            else if (attribute.Json)
                await writer.WriteAsync((string)value, NpgsqlDbType.Varchar, cancellationToken);
            //A declared type name leaves the choice to Npgsql, with the two corrections below.
            else if (!string.IsNullOrEmpty(attribute.TypeName))
                await writer.WriteAsync(Normalize(value), cancellationToken);
            else if (type.IsEnum)
                await writer.WriteAsync(Convert.ToInt32(value, CultureInfo.InvariantCulture), NpgsqlDbType.Integer, cancellationToken);
            else if (type == Types.TypeBool)
                await writer.WriteAsync((bool)value, NpgsqlDbType.Boolean, cancellationToken);
            else if (type == Types.TypeByte)
                await writer.WriteAsync((short)(byte)value, NpgsqlDbType.Smallint, cancellationToken);
            else if (type == Types.TypeShort)
                await writer.WriteAsync((short)value, NpgsqlDbType.Smallint, cancellationToken);
            else if (type == Types.TypeInt)
                await writer.WriteAsync((int)value, NpgsqlDbType.Integer, cancellationToken);
            else if (type == Types.TypeLong)
                await writer.WriteAsync((long)value, NpgsqlDbType.Bigint, cancellationToken);
            else if (type == Types.TypeDouble)
                await writer.WriteAsync((double)value, NpgsqlDbType.Double, cancellationToken);
            else if (type == Types.TypeFloat)
                await writer.WriteAsync((float)value, NpgsqlDbType.Real, cancellationToken);
            else if (type == Types.TypeDecimal)
                await writer.WriteAsync((decimal)value, NpgsqlDbType.Numeric, cancellationToken);
            else if (type == Types.TypeGuid)
                await writer.WriteAsync((Guid)value, NpgsqlDbType.Uuid, cancellationToken);
            else if (type == Types.TypeString)
                await writer.WriteAsync((string)value, NpgsqlDbType.Varchar, cancellationToken);
            else if (type == Types.TypeChar)
                await writer.WriteAsync(((char)value).ToString(), NpgsqlDbType.Char, cancellationToken);
            else if (type == Types.TypeByteArray)
                await writer.WriteAsync((byte[])value, NpgsqlDbType.Bytea, cancellationToken);
            else if (type == Types.TypeDateTimeOffset)
                await writer.WriteAsync(((DateTimeOffset)value).UtcDateTime, NpgsqlDbType.TimestampTz, cancellationToken);
            else if (type == Types.TypeDateTime)
                //Whatever its kind: with the type named, Npgsql writes the ticks as they are.
                await writer.WriteAsync((DateTime)value, NpgsqlDbType.Timestamp, cancellationToken);
            else if (type == Types.TypeDateOnly)
                await writer.WriteAsync((DateOnly)value, NpgsqlDbType.Date, cancellationToken);
            else if (type == Types.TypeTimeOnly)
                await writer.WriteAsync((TimeOnly)value, NpgsqlDbType.Time, cancellationToken);
            else if (type == Types.TypeTimeSpan)
                await writer.WriteAsync((TimeSpan)value, NpgsqlDbType.Interval, cancellationToken);
            else
                await writer.WriteAsync(value, cancellationToken);
        }

        //A value written without a type: a DateTimeOffset has to be UTC for Npgsql. (A DateTime of
        //any kind is written as it is; unlike a parameter, COPY does not refuse a Utc one.)
        private static object Normalize(object value) => value is DateTimeOffset moment ? moment.UtcDateTime : value;
    }
}
