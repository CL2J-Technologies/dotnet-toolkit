using cl2j.Database.DataAnnotations;
using cl2j.Database.Databases;
using Microsoft.Extensions.Logging.Abstractions;
using Xunit;

namespace cl2j.Database.IntegrationTests
{
    /// <summary>
    ///     Defects that are filed and not fixed here, and that reach a server. Each test states
    ///     the behaviour the issue asks for and is skipped until the issue is closed; remove the
    ///     <c>Skip</c> with the fix. The one defect that needs no server (the logger that
    ///     <c>UseDatabase</c> publishes) is not here: it stays with SQL Server's tests so that it
    ///     is listed once, not once per provider.
    ///
    ///     <para>
    ///     No hooks: the <c>DateOnly</c> test asks for the same value back on every provider, and
    ///     the two skipped tests go through <see cref="IDatabaseFixture.CreateDatabase"/>.
    ///     </para>
    /// </summary>
    public abstract class KnownDefectTestsBase(IDatabaseFixture fixture)
    {
        [Fact]
        public async Task A_DateOnly_survives_the_write_read_cycle()
        {
            await using var connection = await fixture.OpenAsync();
            await connection.DropTableIfExists(typeof(DateOnlyRow), CancellationToken.None);
            await connection.CreateTable<DateOnlyRow>();
            try
            {
                var id = await connection.NewKey<DateOnlyRow>();
                await connection.Insert(new DateOnlyRow { Id = id, Day = new DateOnly(2026, 9, 27) });

                //The insert succeeds, and an empty table would hide the failure below: it takes a
                //row coming back to throw.
                var read = await connection.QueryKey<DateOnlyRow>(id);

                Assert.Equal(new DateOnly(2026, 9, 27), read!.Day);
            }
            finally
            {
                await connection.DropTableIfExists(typeof(DateOnlyRow), CancellationToken.None);
            }
        }

        [Fact(Skip = "Bug: #69 NewKey only looks at SelfGeneratedKey columns, so it throws for the AutoGeneratedKey entity that Insert fills in")]
        public async Task NewKey_gives_a_key_for_an_auto_generated_key_entity()
        {
            var database = fixture.CreateDatabase(new DatabaseOptions(), NullLogger.Instance);

            var key = await database.NewKey<FacadeRow>();

            Assert.StartsWith("fac_", key, StringComparison.Ordinal);
        }

        [Fact(Skip = "Bug: #69 IDatabase.Insert does not fill in the identity the server picked; only the connection-level Insert<TIn, TOut> returns it")]
        public async Task Insert_through_IDatabase_fills_in_an_identity_key()
        {
            await using (var connection = await fixture.OpenAsync())
            {
                await connection.DropTableIfExists(typeof(FacadeIdentityRow), CancellationToken.None);
                await connection.CreateTable<FacadeIdentityRow>();
            }

            try
            {
                var database = fixture.CreateDatabase(new DatabaseOptions(), NullLogger.Instance);

                var row = await database.Insert(new FacadeIdentityRow { Label = "x" });

                Assert.True(row.Id > 0);
            }
            finally
            {
                await using var connection = await fixture.OpenAsync();
                await connection.DropTableIfExists(typeof(FacadeIdentityRow), CancellationToken.None);
            }
        }
    }

    /// <summary>
    ///     A <see cref="DateOnly"/> mapped to a <c>date</c> column. See issue #46.
    /// </summary>
    [Table("DateOnlyShapes")]
    public sealed class DateOnlyRow
    {
        [Column(Name = "Id", Key = KeyType.SelfGeneratedKey, Length = 50)]
        public string Id { get; set; } = string.Empty;

        [Column(Name = "Day")]
        public DateOnly Day { get; set; }
    }
}
